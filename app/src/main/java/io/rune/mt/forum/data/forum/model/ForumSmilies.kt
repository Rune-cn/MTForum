    /** Flat lookup used to resolve a smiley id back to its image while rendering. */
    val byId: Map<Int, ForumSmiley> by lazy { groups.flatMap { it.smilies }.associateBy { it.id } }

    /**
     * Lookup by BBCode token (`[#呵呵]`). Discuz stores a smiley as this token in the post
     * source and only turns it into an `<img>` at render time, so the client has to do the same.
     */
    val byCode: Map<String, ForumSmiley> by lazy {
        // Codes are not globally unique (滑稽 and QQ both define [#呵呵]); keep the first so the
        // mapping is deterministic and follows the tab order the site shows.
        buildMap { groups.forEach { g -> g.smilies.forEach { s -> putIfAbsent(s.code, s) } } }
    }
