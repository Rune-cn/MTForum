/**
 * One Discuz smiley.
 *
 * The catalogue comes from the CDN file data/cache/common_smilies_var.js, which declares each
 * category as a [label, directory] pair and each smiley as [id, BBCode code, file name]. The
 * tables below are generated from it; regenerate them if the site adds smilies.
 */
